#!/usr/bin/env python3
"""Copies the runtime's function-local built-in shader literals verbatim into
builtin_sources.inc, so LoShaderPackTool builtin-requests compiles exactly the
text the runtime does. Literal tokens are copied as written (raw or escaped),
so the C++ compiler gives them the same value it gives the runtime."""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2] / "LostOdysseyRecomp"
# (alias, file, anchor text the assignment follows, assignment regex)
SPECS = [
    ("kPresentSource",      "gpu/presentation.cpp", "", r"const char \*source = "),
    ("kPresentCompute",     "gpu/presentation.cpp", "InitCompute(const char *pixelSource)\n{", r"const char \*computeSource = "),
    ("kPresentUi",          "gpu/presentation.cpp", "", r"const char \*uiSource = "),
    ("kPresentOverlay",     "gpu/presentation.cpp", "", r"const char \*overlaySource = "),
    ("kTaaSource",          "gpu/temporal_aa.cpp",  "", r"const char\* source="),
    ("kTransferBindings",   "gpu/renderer.cpp", "void CompileTransferShader()", r"const char\* bindings =\s*"),
    ("kBlitVs",             "gpu/renderer.cpp", "void CompileBlitShaders()", r"const char\* vsSrc =\s*"),
    ("kBlitPs",             "gpu/renderer.cpp", "void CompileBlitShaders()", r"const char\* psSrc =\s*"),
    ("kRectListGs",         "gpu/renderer.cpp", "void CompileRectListGs()", r"std::string src = "),
    ("kSmaaPrefix",         "gpu/shader/smaa_pipeline.h", "", r"std::string hlsl="),
    ("kSmaaPasses",         "gpu/shader/smaa_pipeline.h", "hlsl+=smaa;", r"hlsl\+=(?=R)"),
    ("kDlssFgDepth",        "gpu/dlss_fg_depth.cpp", "", r"constexpr const char\* kShader = "),
    ("kMvMaskShader",       "gpu/motion_replay_gpu.h", "", r"static constexpr const char\* kMaskShader = "),
    ("kMvCameraHlsl",       "gpu/motion_replay_gpu.h", "", r"static constexpr const char\* kCameraHlsl = "),
    ("kMvCameraMaskShader", "gpu/motion_replay_gpu.h", "", r"static constexpr const char\* kCameraMaskShader = "),
    ("kMvCameraMaskBody",   "gpu/motion_replay_gpu.h", "", r"static constexpr const char\* kCameraMaskBody = "),
    ("kMvCameraFillShader", "gpu/motion_replay_gpu.h", "", r"static constexpr const char\* kCameraFillShader = "),
    ("kMvCameraFillBody",   "gpu/motion_replay_gpu.h", "", r"static constexpr const char\* kCameraFillBody = "),
]
LIT = re.compile(r'R"([^(\s]{0,16})\(|"')

def literals(text, pos):
    """Adjacent string-literal tokens starting at pos; returns (verbatim, end)."""
    out, i = [], pos
    while True:
        while i < len(text) and text[i] in " \t\r\n": i += 1
        m = LIT.match(text, i)
        if not m: break
        if m.group(0).startswith("R"):
            end = text.index(")" + m.group(1) + '"', m.end()) + len(m.group(1)) + 2
        else:
            j = i + 1
            while text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            end = j + 1
        out.append(text[i:end]); i = end
    if not out: raise SystemExit(f"no literal at {pos}: {text[pos:pos+60]!r}")
    return "\n".join(out), i

lines = ["// Generated by extract_builtin_sources.py from the runtime sources. Do not edit.", "#pragma once"]
for alias, file, anchor, pattern in SPECS:
    text = (ROOT / file).read_text()
    start = text.index(anchor) if anchor else 0
    matches = list(re.finditer(pattern, text[start:]))
    if not matches: raise SystemExit(f"{alias}: {pattern} not found in {file}")
    if not anchor and len(matches) != 1: raise SystemExit(f"{alias}: {len(matches)} matches in {file}")
    body, _ = literals(text, start + matches[0].end())
    lines.append(f"inline constexpr const char* {alias} =\n{body};")
pathlib.Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
print(f"{len(SPECS)} literals -> {sys.argv[1]}")
